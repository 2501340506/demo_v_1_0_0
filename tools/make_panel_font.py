"""Glyph ROM and string codes for the v0.27 SW4 adjust panel.

Renders every glyph the panel uses at 16x16 with SimSun (as the scene FONT.BIN),
ASCII half width in the left 8 columns, into user_source/hdl_source/adjust/panel_font_rom.v:
64 glyphs x 16 rows x 16 bits, a registered read, so it maps to block RAM and costs
almost no LUTs. Text is laid out on 8 px half cells: ASCII takes one, Chinese two.
Each string is written as packed 7-bit half-cell entries {right half, glyph code}
between the markers in adjust_osd_overlay.v, so no Chinese text appears in the RTL.
Run: python -I -X utf8 tools/make_panel_font.py [path/to/simsun.ttc]
"""
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
ROM = ROOT / "user_source/hdl_source/adjust/panel_font_rom.v"
OVERLAY = ROOT / "user_source/hdl_source/adjust/adjust_osd_overlay.v"
BEGIN = " // panel glyph codes: generated by tools/make_panel_font.py, do not edit\n"
END = " // end of generated panel glyph codes\n"

ASCII = " 0123456789%X-K"         # half width; everything else is full width
STRINGS = {   # name: (half cells, text); shorter text is padded with blanks on the right
    "S_TITLE": (8, "参数调节"),
    "S_HINT_MOVE": (16, "K1↑ K2↓ K4编辑"),
    "S_HINT_EDIT": (16, "K1↑ K2↓ K4返回"),
    "S_CAT0": (4, "画面"), "S_CAT1": (4, "声音"), "S_CAT2": (4, "波形"),
    "S_CAT3": (4, "场景"), "S_CAT4": (4, "功能"), "S_CAT5": (4, "重置"),
    "S_ITEM0": (8, "亮度"), "S_ITEM1": (8, "对比度"), "S_ITEM2": (8, "音量"),
    "S_ITEM3": (8, "显示"), "S_ITEM4": (8, "高度"), "S_ITEM5": (8, "渐变"),
    "S_ITEM6": (8, "速度"), "S_ITEM7": (8, "状态栏"), "S_ITEM8": (8, "字幕"),
    "S_ITEM9": (8, "淡入"), "S_ITEM10": (8, "全部重置"),
    "S_ON": (2, "开"), "S_OFF": (2, "关"), "S_HOLD": (6, "长按K4"),
}


def main():
    face_path = sys.argv[1] if len(sys.argv) > 1 else "simsun.ttc"
    face = ImageFont.truetype(face_path, 16)
    glyphs = list(ASCII) + list(dict.fromkeys(
        c for _, text in STRINGS.values() for c in text if c not in ASCII))
    if len(glyphs) > 64:
        raise SystemExit(f"{len(glyphs)} glyphs, the ROM holds 64")
    code = {c: i for i, c in enumerate(glyphs)}
    rows = []
    for c in glyphs + [" "] * (64 - len(glyphs)):
        image = Image.new("1", (16, 16))
        ImageDraw.Draw(image).text((0, 0), c, font=face, fill=1)
        data = image.tobytes()                  # 2 bytes per row, leftmost pixel = bit 15
        rows += [data[2 * r] << 8 | data[2 * r + 1] for r in range(16)]
    lines = ["// Generated by tools/make_panel_font.py: adjust panel glyphs, SimSun 16x16.",
             "// address = {glyph code, row}; data bit 15 is the leftmost pixel.",
             "// Registered read without reset, so synthesis maps it to block RAM.",
             "module panel_font_rom(input wire clk, input wire [9:0] address, output reg [15:0] data);",
             "reg [15:0] glyphs [0:1023];", "initial begin"]
    lines += [f"glyphs[{i}] = 16'h{v:04x};" for i, v in enumerate(rows)]
    lines += ["end", "always @(posedge clk) data <= glyphs[address];", "endmodule", ""]
    ROM.write_text("\n".join(lines), encoding="ascii", newline="\n")

    block = [BEGIN, f" // {len(glyphs)} glyphs; entries are {{right half, code}}; digits are G_D0+n.\n",
             " localparam [5:0] G_SP=6'd0,G_D0=6'd1,G_PCT=6'd11,G_X=6'd12,G_DASH=6'd13;\n"]
    for name, (cells, text) in STRINGS.items():
        entries = [e for c in text for e in ([code[c]] if c in ASCII else [code[c], 64 + code[c]])]
        if len(entries) > cells:
            raise SystemExit(f"{name} needs {len(entries)} half cells, has {cells}")
        entries += [0] * (cells - len(entries))
        packed = ",".join(f"7'd{v}" for v in entries)
        block.append(f" localparam [{7 * cells - 1}:0] {name}={{{packed}}};  // {text}\n")
    block.append(END)
    source = OVERLAY.read_text(encoding="utf-8")
    head, rest = source.split(BEGIN)
    _, tail = rest.split(END)
    OVERLAY.write_text(head + "".join(block) + tail, encoding="utf-8", newline="\n")
    print(f"{len(glyphs)} glyphs -> {ROM.name}; {len(STRINGS)} strings -> {OVERLAY.name}")


if __name__ == "__main__":
    main()
