"""Generate a synchronous quadrant ROM; no runtime file-path dependency."""
from pathlib import Path
import math

ROOT = Path(__file__).resolve().parents[1]

def geometry(x, y):
    radius = math.hypot(x, y)
    if 52 <= radius < 64:
        return 1 << 10
    angle = math.atan2(y, x)
    bar = round(angle * 48 / math.pi)
    theta = bar * math.pi / 48
    along = x * math.cos(theta) + y * math.sin(theta)
    across = abs(-x * math.sin(theta) + y * math.cos(theta))
    # Capsule: 3px diameter, start cap centered at radius 65.5.
    for height in range(29):
        distance = math.hypot(across, max(65.5 - along, along - (65.5 + height), 0))
        if distance <= 1.5:
            return (2 << 10) | (bar << 5) | height
    return 0

def main():
    target = ROOT / 'user_source/hdl_source/audio_vis/audio_ring_rom.v'
    target.parent.mkdir(parents=True, exist_ok=True)
    lines = ['// Generated by tools/generate_audio_ring.py; 96x96 quadrant, 12 bits.',
             'module audio_ring_rom(input wire clk, input wire [13:0] address, output reg [11:0] data);',
             'reg [11:0] geometry [0:9215];', 'initial begin']
    lines.extend(f"geometry[{y*96+x}] = 12'h{geometry(x,y):03x};" for y in range(96) for x in range(96))
    lines += ['end', 'always @(posedge clk) data <= geometry[address];', 'endmodule', '']
    target.write_text('\n'.join(lines), encoding='utf-8')
    print(f'Generated {target}: 9216 x 12 bits')

if __name__ == '__main__':
    main()
