// Former parameter OSD. v0.27: B/C/V moved to the SW4 panel and the scene
// SPEED line was removed, so it draws nothing; it only converts brightness,
// contrast and volume to decimal for the panel. Ports are kept for callers.
module adjust_osd_overlay #(parameter ENABLE=1,SCENE_ENABLE=0)(
 input clk,rst,vs,de,input [9:0] pixel_x,input [23:0] rgb_in,
 input [1:0] mode,selected,input [7:0] brightness,contrast,input [4:0] volume_level,
 input scene_enable,input [1:0] scene_speed,
 output [23:0] rgb_out,output active,
 output [11:0] bright_bcd,contrast_bcd,volume_bcd
);
 wire frame_start;
 osd_pixel_position position(.clk(clk),.rst(rst),.vs(vs),.de(de),.line_y(),.frame_start(frame_start),.first_active());
 // Shared eight-step binary-to-BCD converter runs in vertical blanking.
 reg [11:0] b_bcd,c_bcd,v_bcd;
 reg [19:0] shift;
 reg [1:0] phase;
 reg [2:0] bit_count;
 reg [19:0] corrected;
 always @*begin
  corrected=shift;
  if(shift[11:8]>=5)corrected[11:8]=shift[11:8]+4'd3;
  if(shift[15:12]>=5)corrected[15:12]=shift[15:12]+4'd3;
  if(shift[19:16]>=5)corrected[19:16]=shift[19:16]+4'd3;
 end
 wire [19:0] shifted=corrected<<1;
 wire [7:0] volume={3'd0,volume_level}*8'd10;
 always @(posedge clk or posedge rst)begin
  if(rst)begin b_bcd<=12'h128;c_bcd<=12'h128;v_bcd<=12'h100;shift<=0;phase<=3;bit_count<=0;end
  else if(frame_start)begin shift<={12'd0,brightness};phase<=0;bit_count<=0;end
  else if(phase!=3)begin
   if(bit_count==7)begin
    bit_count<=0;phase<=phase+1'b1;
    case(phase)
     0:begin b_bcd<=shifted[19:8];shift<={12'd0,contrast};end
     1:begin c_bcd<=shifted[19:8];shift<={12'd0,volume};end
     2:begin v_bcd<=shifted[19:8];shift<=0;end
    endcase
   end else begin shift<=shifted;bit_count<=bit_count+1'b1;end
  end
 end
 assign bright_bcd=b_bcd;assign contrast_bcd=c_bcd;assign volume_bcd=v_bcd;
 assign rgb_out=rgb_in;
 assign active=1'b0;
endmodule

// v0.27 adjust panel (SW4): 336x200 at x=296,y=120, slides in from the right
// over eight frames. Title, then two columns: categories, and the items of the
// current category with value text and bars; key hints at the bottom. Text is
// 16x16 Chinese from panel_font_rom (block RAM). Rendered through two registers,
// so the panel lands 2 px right of its nominal place; video latency is unchanged.
module adjust_panel_overlay #(parameter ENABLE=1)(
 input clk,rst,vs,de,input [9:0] pixel_x,input [23:0] rgb_in,
 input panel,focus,input [3:0] item,
 input [7:0] brightness,contrast,input [4:0] volume_level,
 input wave_on,input [1:0] wave_height,wash_level,input osd_on,scroll_on,fade_on,
 input [11:0] bright_bcd,contrast_bcd,volume_bcd,
 input scene_on,input [1:0] scene_speed,   // scenario_fsm speed (0 1X, 1 2X, 2 4X)
 output [23:0] rgb_out
);
 localparam [9:0] X0=10'd296;
 localparam [8:0] Y0=9'd120;
 localparam [23:0] C_BG=24'h102030,C_BLUE=24'h3c82f0,C_DIM=24'h1c3c6c,
                   C_TRACK=24'h2a3c54,C_WHITE=24'hffffff,C_GRAY=24'h8ca0b8;
 // panel glyph codes: generated by tools/make_panel_font.py, do not edit
 // 61 glyphs; entries are {right half, code}; digits are G_D0+n.
 localparam [5:0] G_SP=6'd0,G_D0=6'd1,G_PCT=6'd11,G_X=6'd12,G_DASH=6'd13;
 localparam [55:0] S_TITLE={7'd15,7'd79,7'd16,7'd80,7'd17,7'd81,7'd18,7'd82};  // 参数调节
 localparam [111:0] S_HINT_MOVE={7'd14,7'd2,7'd19,7'd83,7'd0,7'd14,7'd3,7'd20,7'd84,7'd0,7'd14,7'd5,7'd21,7'd85,7'd22,7'd86};  // K1↑ K2↓ K4编辑
 localparam [111:0] S_HINT_EDIT={7'd14,7'd2,7'd19,7'd83,7'd0,7'd14,7'd3,7'd20,7'd84,7'd0,7'd14,7'd5,7'd23,7'd87,7'd24,7'd88};  // K1↑ K2↓ K4返回
 localparam [27:0] S_CAT0={7'd25,7'd89,7'd26,7'd90};  // 画面
 localparam [27:0] S_CAT1={7'd27,7'd91,7'd28,7'd92};  // 声音
 localparam [27:0] S_CAT2={7'd29,7'd93,7'd30,7'd94};  // 波形
 localparam [27:0] S_CAT3={7'd31,7'd95,7'd32,7'd96};  // 场景
 localparam [27:0] S_CAT4={7'd33,7'd97,7'd34,7'd98};  // 功能
 localparam [27:0] S_CAT5={7'd35,7'd99,7'd36,7'd100};  // 重置
 localparam [55:0] S_ITEM0={7'd37,7'd101,7'd38,7'd102,7'd0,7'd0,7'd0,7'd0};  // 亮度
 localparam [55:0] S_ITEM1={7'd39,7'd103,7'd40,7'd104,7'd38,7'd102,7'd0,7'd0};  // 对比度
 localparam [55:0] S_ITEM2={7'd28,7'd92,7'd41,7'd105,7'd0,7'd0,7'd0,7'd0};  // 音量
 localparam [55:0] S_ITEM3={7'd42,7'd106,7'd43,7'd107,7'd0,7'd0,7'd0,7'd0};  // 显示
 localparam [55:0] S_ITEM4={7'd44,7'd108,7'd38,7'd102,7'd0,7'd0,7'd0,7'd0};  // 高度
 localparam [55:0] S_ITEM5={7'd45,7'd109,7'd46,7'd110,7'd0,7'd0,7'd0,7'd0};  // 渐变
 localparam [55:0] S_ITEM6={7'd47,7'd111,7'd38,7'd102,7'd0,7'd0,7'd0,7'd0};  // 速度
 localparam [55:0] S_ITEM7={7'd48,7'd112,7'd49,7'd113,7'd50,7'd114,7'd0,7'd0};  // 状态栏
 localparam [55:0] S_ITEM8={7'd51,7'd115,7'd52,7'd116,7'd0,7'd0,7'd0,7'd0};  // 字幕
 localparam [55:0] S_ITEM9={7'd53,7'd117,7'd54,7'd118,7'd0,7'd0,7'd0,7'd0};  // 淡入
 localparam [55:0] S_ITEM10={7'd55,7'd119,7'd56,7'd120,7'd35,7'd99,7'd36,7'd100};  // 全部重置
 localparam [13:0] S_ON={7'd57,7'd121};  // 开
 localparam [13:0] S_OFF={7'd58,7'd122};  // 关
 localparam [41:0] S_HOLD={7'd59,7'd123,7'd60,7'd124,7'd14,7'd5};  // 长按K4
 // end of generated panel glyph codes
 wire [8:0] y;wire frame_start;
 osd_pixel_position position(.clk(clk),.rst(rst),.vs(vs),.de(de),.line_y(y),.frame_start(frame_start),.first_active());
 reg [8:0] off;reg [9:0] x0;
 always @(posedge clk or posedge rst)
  if(rst)begin off<=9'd336;x0<=10'd632;end
  else if(frame_start)begin
   if(ENABLE && panel)off<=off>=42?off-9'd42:9'd0;
   else off<=off>=294?9'd336:off+9'd42;
   x0<=X0+off;
  end
 wire shown=ENABLE && off!=9'd336;
 // Category layout of the item list.
 reg [2:0] cat;reg [3:0] first;reg [1:0] count;
 always @*begin
  case(item)0,1:cat=0;2:cat=1;3,4,5:cat=2;6:cat=3;7,8,9:cat=4;default:cat=5;endcase
  case(cat)0:begin first=0;count=2;end 1:begin first=2;count=1;end
   2:begin first=3;count=3;end 3:begin first=6;count=1;end 4:begin first=7;count=3;end
   default:begin first=10;count=1;end
  endcase
 end
 // Text entries are 8 px half cells {right half, glyph}: ASCII one, Chinese two.
 localparam [6:0] H_SP={1'b0,G_SP},H_PCT={1'b0,G_PCT},H_X={1'b0,G_X},H_DASH={1'b0,G_DASH};
 function [6:0] digit(input [3:0] d);digit={1'b0,G_D0+{2'd0,d}};endfunction
 function [41:0] onoff(input on);onoff={H_SP,H_SP,H_SP,H_SP,on?S_ON:S_OFF};endfunction
 function [7:0] level_fill(input [1:0] v);
  case(v)0:level_fill=0;1:level_fill=58;2:level_fill=117;default:level_fill=176;endcase
 endfunction
 // Vertical decode once per line (y only changes in horizontal blanking).
 // Text rows are 16 lines: title 3..18, categories 32+24i, items 32+48i, hints 179..194.
 wire [8:0] ly=y-Y0;
 reg n_in,n_frame,n_title_band,n_title,n_hint,n_cat_text,n_cat_hl,n_item_text,n_item_hl,n_bar,n_body;
 reg [2:0] n_cat;reg [3:0] n_grow;reg [1:0] n_row;reg [8:0] t,s;
 integer i;
 always @*begin
  n_in=y>=Y0 && y<Y0+9'd200;n_frame=ly<2 || ly>=198;n_title_band=ly<22;n_body=ly<9'd176;
  n_title=0;n_hint=0;n_cat_text=0;n_cat_hl=0;n_item_text=0;n_item_hl=0;n_bar=0;
  n_cat=0;n_row=0;n_grow=0;t=0;s=0;
  if(ly>=3 && ly<19)begin n_title=1;t=ly-9'd3;n_grow=t[3:0];end
  if(ly>=179 && ly<195)begin n_hint=1;t=ly-9'd179;n_grow=t[3:0];end
  for(i=0;i<6;i=i+1)begin
   s=9'd32+9'd24*i;
   if(ly+9'd4>=s && ly<s+9'd20)begin n_cat_hl=1;n_cat=i;end
   if(ly>=s && ly<s+9'd16)begin n_cat_text=1;t=ly-s;n_grow=t[3:0];end
  end
  for(i=0;i<3;i=i+1)begin
   s=9'd32+9'd48*i;
   if(ly+9'd4>=s && ly<s+9'd44)n_row=i;
   if(ly+9'd4>=s && ly<s+9'd20)n_item_hl=1;
   if(ly>=s && ly<s+9'd16)n_item_text=1;
   if(ly>=s+9'd20 && ly<s+9'd28)n_bar=1;
  end
 end
 wire [3:0] n_item=first+n_row;
 // Values: six half cells, right aligned.
 reg [41:0] n_value;reg [7:0] n_fill;reg n_has_bar;
 always @*begin
  n_has_bar=0;n_fill=0;n_value={6{H_SP}};
  case(n_item)
   0:begin n_value={H_SP,H_SP,H_SP,digit(bright_bcd[11:8]),digit(bright_bcd[7:4]),digit(bright_bcd[3:0])};
      n_has_bar=1;n_fill=({4'd0,brightness}*12'd11)>>4;end
   1:begin n_value={H_SP,H_SP,H_SP,digit(contrast_bcd[11:8]),digit(contrast_bcd[7:4]),digit(contrast_bcd[3:0])};
      n_has_bar=1;n_fill=({4'd0,contrast}*12'd11)>>4;end
   2:begin n_value={H_SP,H_SP,digit(volume_bcd[11:8]),digit(volume_bcd[7:4]),digit(volume_bcd[3:0]),H_PCT};
      n_has_bar=1;n_fill={volume_level,3'd0}+{3'd0,volume_level};end // 9 px per 10%
   3:n_value=onoff(wave_on);
   4:begin n_value={{5{H_SP}},digit({2'd0,wave_height})};n_has_bar=1;n_fill=level_fill(wave_height);end
   5:begin n_value={{5{H_SP}},digit({2'd0,wash_level})};n_has_bar=1;n_fill=level_fill(wash_level);end
   6:n_value=scene_on?{{4{H_SP}},digit(scene_speed==0?4'd1:scene_speed==1?4'd2:4'd4),H_X}:
                      {{4{H_SP}},H_DASH,H_DASH};
   7:n_value=onoff(osd_on);
   8:n_value=onoff(scroll_on);
   9:n_value=onoff(fade_on);
   default:n_value=S_HOLD;
  endcase
 end
 reg v_body,v_in,v_frame,v_title_band,v_title,v_hint,v_cat_text,v_cat_hl,v_item_text,v_item_hl,v_bar,v_valid,v_has_bar,v_cur_cat,v_cur_item;
 reg [2:0] v_cat;reg [3:0] v_grow,v_item;reg [41:0] v_value;reg [7:0] v_fill;
 always @(posedge clk or posedge rst)
  if(rst)begin
   v_body<=0;v_in<=0;v_frame<=0;v_title_band<=0;v_title<=0;v_hint<=0;v_cat_text<=0;v_cat_hl<=0;
   v_item_text<=0;v_item_hl<=0;v_bar<=0;v_valid<=0;v_has_bar<=0;v_cur_cat<=0;v_cur_item<=0;
   v_cat<=0;v_grow<=0;v_item<=0;v_value<=0;v_fill<=0;
  end else begin
   v_body<=n_body;v_in<=n_in;v_frame<=n_frame;v_title_band<=n_title_band;v_title<=n_title;v_hint<=n_hint;
   v_cat_text<=n_cat_text;v_cat_hl<=n_cat_hl;v_item_text<=n_item_text;v_item_hl<=n_item_hl;v_bar<=n_bar;
   v_valid<=n_row<count;v_has_bar<=n_has_bar;v_cur_cat<=n_cat==cat;v_cur_item<=n_item==item;
   v_cat<=n_cat;v_grow<=n_grow;v_item<=n_item;v_value<=n_value;v_fill<=n_fill;
  end
 reg [27:0] cat_str;reg [55:0] item_str;
 always @*begin
  case(v_cat)0:cat_str=S_CAT0;1:cat_str=S_CAT1;2:cat_str=S_CAT2;3:cat_str=S_CAT3;4:cat_str=S_CAT4;
   default:cat_str=S_CAT5;endcase
  case(v_item)0:item_str=S_ITEM0;1:item_str=S_ITEM1;2:item_str=S_ITEM2;3:item_str=S_ITEM3;
   4:item_str=S_ITEM4;5:item_str=S_ITEM5;6:item_str=S_ITEM6;7:item_str=S_ITEM7;
   8:item_str=S_ITEM8;9:item_str=S_ITEM9;default:item_str=S_ITEM10;endcase
 end
 // Half cells of 8 px: title (8) centred at x 136, hints (16) centred at x 104,
 // categories at x 48, item names at x 144, values right aligned to x 320.
 wire [9:0] lx=pixel_x-x0;
 wire in_x=pixel_x>=x0 && lx<10'd336;
 wire [6:0] hc=lx[9:3];
 wire [111:0] hint=focus?S_HINT_EDIT:S_HINT_MOVE;
 reg [6:0] entry;reg [1:0] ink,paper;
 always @*begin
  entry=H_SP;ink=1;
  if(v_title && hc>=17 && hc<25)entry=S_TITLE[55-7*(hc-17) -: 7];
  else if(v_hint && hc>=13 && hc<29)begin entry=hint[111-7*(hc-13) -: 7];ink=2;end
  else if(v_cat_text && hc>=6 && hc<10)entry=cat_str[27-7*(hc-6) -: 7];
  else if(v_item_text && v_valid && hc>=18 && hc<26)entry=item_str[55-7*(hc-18) -: 7];
  else if(v_item_text && v_valid && hc>=34 && hc<40)entry=v_value[41-7*(hc-34) -: 7];
  // paper 0 bg, 1 blue, 2 dim, 3 bar track
  paper=0;
  if(v_frame || lx<2 || lx>=334 || v_title_band || (v_body && lx>=128 && lx<130))paper=1;
  else if(v_cat_hl && v_cur_cat && lx>=8 && lx<124)paper=focus?2'd2:2'd1;
  else if(v_item_hl && v_valid && v_cur_item && lx>=134 && lx<330)paper=focus?2'd1:2'd2;
  else if(v_bar && v_valid && v_has_bar && lx>=144 && lx<320)paper=(lx-10'd144)<{2'd0,v_fill}?2'd1:2'd3;
 end
 // The ROM read is the first register stage, in step with hit1.
 wire [15:0] glyph_row;
 panel_font_rom font(.clk(clk),.address({entry[5:0],v_grow}),.data(glyph_row));
 wire [3:0] gx={entry[6],lx[2:0]};
 reg hit1;reg [3:0] gx1;reg [1:0] ink1,paper1;
 reg hit2;reg [23:0] color2;
 wire glyph_on=glyph_row[~gx1];
 always @(posedge clk or posedge rst)
  if(rst)begin hit1<=0;gx1<=0;ink1<=0;paper1<=0;hit2<=0;color2<=0;end
  else begin
   hit1<=shown && de && v_in && in_x;gx1<=gx;ink1<=ink;paper1<=paper;
   hit2<=hit1;
   color2<=glyph_on?(ink1==2?C_GRAY:C_WHITE):
    paper1==1?C_BLUE:paper1==2?C_DIM:paper1==3?C_TRACK:C_BG;
  end
 assign rgb_out=hit2?color2:rgb_in;
endmodule
