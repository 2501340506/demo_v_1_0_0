"""Derive tb_scanner_s2_equivalence.sv from the S1 bench.

Stimulus, sector model and coverage gates stay identical. Both sides use the
S2 indexed port list: the reference is scanner_s1_indexed (S1 register tables
behind the original consumer muxes). image/audio indexes are randomized each
cycle; a table row is compared only while its valid/found bit is set.
"""
import re
import sys

src, dst = sys.argv[1], sys.argv[2]
s = open(src, encoding='utf-8').read().replace('\r\n', '\n')


def rep(a, b, count=1):
    global s
    n = s.count(a)
    assert n == count, (a[:60], n)
    s = s.replace(a, b)


start = s.index('`define SCANNER_PORTS(p)')
end = s.index(' integer seed=SEED;')
s = s[:start] + r'''`define SCANNER_PORTS(p) \
  .clk(clk),.rst_n(rst_n),.scan_start(scan_start),.directory_cluster(directory_cluster), \
  .directory_valid(p``_directory_valid),.directory_clusters(p``_directory_clusters), \
  .scan_busy(p``_scan_busy),.scan_done(p``_scan_done),.fs_error(p``_fs_error), \
  .partition_lba(p``_partition_lba),.sectors_per_cluster(p``_spc), \
  .fat_start_lba(p``_fat_start),.data_start_lba(p``_data_start),.max_cluster(p``_max_cluster), \
  .resource_valid(p``_resource_valid),.thumb_found(p``_thumb_found), \
  .image_index(image_index),.image_cluster(p``_image_cluster),.image_size(p``_image_size), \
  .audio_found(p``_audio_found),.snd_valid(p``_snd_valid), \
  .audio_index(audio_index),.audio_entry_cluster(p``_audio_cluster),.audio_entry_size(p``_audio_size), \
  .font_found(p``_font_found),.text_found(p``_text_found), \
  .font_cluster(p``_font_cluster),.font_size(p``_font_size),.text_cluster(p``_text_cluster),.text_size(p``_text_size), \
  .edu_valid(p``_edu_valid),.voi_valid(p``_voi_valid),.voi_invalid(p``_voi_invalid), \
  .sector_req(p``_sector_req),.sector_lba(p``_sector_lba), \
  .sector_busy(sector_busy),.sector_valid(sector_valid),.sector_byte(sector_byte), \
  .sector_byte_index(sector_byte_index),.sector_done(sector_done),.sector_error(sector_error)

`define SCANNER_WIRES(p) \
 wire [5:0] p``_directory_valid; wire [191:0] p``_directory_clusters; \
 wire p``_scan_busy,p``_scan_done; wire [7:0] p``_fs_error,p``_spc; \
 wire [31:0] p``_partition_lba,p``_fat_start,p``_data_start,p``_max_cluster; \
 wire [3:0] p``_resource_valid; wire p``_thumb_found,p``_audio_found; \
 wire [31:0] p``_image_cluster,p``_image_size,p``_audio_cluster,p``_audio_size; \
 wire [3:0] p``_snd_valid; \
 wire p``_font_found,p``_text_found; wire [31:0] p``_font_cluster,p``_font_size,p``_text_cluster,p``_text_size; \
 wire [3:0] p``_edu_valid,p``_voi_valid,p``_voi_invalid; \
 wire p``_sector_req; wire [31:0] p``_sector_lba; \
 wire [1023:0] p``_all={p``_directory_valid,p``_directory_clusters,p``_scan_busy,p``_scan_done,p``_fs_error,p``_spc, \
  p``_partition_lba,p``_fat_start,p``_data_start,p``_max_cluster,p``_resource_valid,p``_thumb_found, \
  p``_audio_found,p``_snd_valid,p``_font_found,p``_text_found, \
  p``_font_cluster,p``_font_size,p``_text_cluster,p``_text_size, \
  p``_edu_valid,p``_voi_valid,p``_voi_invalid,p``_sector_req,p``_sector_lba};

 reg [3:0] image_index=0, audio_index=0;
 `SCANNER_WIRES(r)
 `SCANNER_WIRES(n)
 scanner_s1_indexed #(.MAX_VISITED_CLUSTERS(8),.DIRECTORY_ENABLE(DIRECTORY_ENABLE),
  .REUSE_GEOMETRY(REUSE_GEOMETRY),.SCAN_AUDIO(SCAN_AUDIO),.SCAN_TEXT(SCAN_TEXT),.SCAN_PUBLICITY(SCAN_PUBLICITY))
  ref_wrap(`SCANNER_PORTS(r));
 fat32_volume_scanner #(.MAX_VISITED_CLUSTERS(8),.DIRECTORY_ENABLE(DIRECTORY_ENABLE),
  .REUSE_GEOMETRY(REUSE_GEOMETRY),.SCAN_AUDIO(SCAN_AUDIO),.SCAN_TEXT(SCAN_TEXT),.SCAN_PUBLICITY(SCAN_PUBLICITY))
  new_scanner(`SCANNER_PORTS(n));
 // Row validity, as the consumers gate it: PIC/EDU/THUMB and BGM/SND/VOI.
 wire image_row_valid=image_index<4 ? r_resource_valid[image_index[1:0]] :
  image_index<8 ? r_edu_valid[image_index[1:0]] : image_index==8 && r_thumb_found;
 wire audio_row_valid=audio_index==0 ? r_audio_found :
  audio_index[3:2]==1 ? r_snd_valid[audio_index[1:0]] : audio_index[3:2]==2 && r_voi_valid[audio_index[1:0]];
 integer row_checks=0,image_rows=0,audio_rows=0,thumb_rows=0,voi_rows=0;

''' + s[end:]

rep('module tb_scanner_s1_equivalence;', 'module tb_scanner_s2_equivalence;')
rep('// v0.24 S1: original and reduced fat32_volume_scanner share one randomized\n'
    '// sector model. Every output, including sector_lba, is compared every cycle.',
    '// v0.24 S2 (generated by make_scanner_s2_bench.py from the S1 bench): the S1\n'
    '// register-table scanner and the S2 RAM-table scanner share one sector model.\n'
    '// Non-table outputs are compared every cycle; table rows while valid.')
s = s.replace('ref_scanner.', 'ref_wrap.core.')
# Coverage probes use the S1 reference's signal names.
rep('ref_wrap.core.flags[7] && ref_wrap.core.flags[0]', 'ref_wrap.core.active_fat1')
rep('ref_wrap.core.mbr_match!=0 && !ref_wrap.core.mbr_match[0]',
    'ref_wrap.core.mbr_found && ref_wrap.core.partition_lba==0 && ref_wrap.core.mbr_lba!=0')
rep('''  if(r_all!==n_all)begin
   mismatches=mismatches+1;
   if(mismatches<=5)$display("MISMATCH t=%0t state=%0d diff=%h",$time,ref_wrap.core.state,r_all^n_all);
  end''', '''  if(r_all!==n_all)begin
   mismatches=mismatches+1;
   if(mismatches<=5)$display("MISMATCH t=%0t state=%0d diff=%h",$time,ref_wrap.core.state,r_all^n_all);
  end
  if(image_row_valid)begin
   row_checks=row_checks+1;image_rows=image_rows+1;if(image_index==8)thumb_rows=thumb_rows+1;
   if({r_image_cluster,r_image_size}!=={n_image_cluster,n_image_size})begin
    mismatches=mismatches+1;
    if(mismatches<=5)$display("IMAGE ROW MISMATCH t=%0t row=%0d ref=%h/%h new=%h/%h",$time,image_index,r_image_cluster,r_image_size,n_image_cluster,n_image_size);
   end
  end
  if(audio_row_valid)begin
   row_checks=row_checks+1;audio_rows=audio_rows+1;if(audio_index[3])voi_rows=voi_rows+1;
   if({r_audio_cluster,r_audio_size}!=={n_audio_cluster,n_audio_size})begin
    mismatches=mismatches+1;
    if(mismatches<=5)$display("AUDIO ROW MISMATCH t=%0t row=%0d ref=%h/%h new=%h/%h",$time,audio_index,r_audio_cluster,r_audio_size,n_audio_cluster,n_audio_size);
   end
  end''')
# Indexes change every cycle, independent of the scan stimulus stream.
rep(' integer scan_count=0,idle_wait;', ''' integer index_seed=SEED*7+3;
 always @(posedge clk)begin
  image_index<=$unsigned($random(index_seed))%10;
  audio_index<=$unsigned($random(index_seed))%12;
 end
 integer scan_count=0,idle_wait;''')
rep('mirror=%0d resources=%0d publicity=%0d",', 'mirror=%0d resources=%0d publicity=%0d image_rows=%0d audio_rows=%0d thumb_rows=%0d voi_rows=%0d",')
rep('mirror_used,resource_hits,publicity_hits);', 'mirror_used,resource_hits,publicity_hits,image_rows,audio_rows,thumb_rows,voi_rows);')
rep("(SCAN_PUBLICITY && publicity_hits<3) ||", "(SCAN_PUBLICITY && publicity_hits<3) || image_rows<10000 || (SCAN_AUDIO && audio_rows<10000) ||\n          (DIRECTORY_ENABLE && thumb_rows<100) || (SCAN_PUBLICITY && voi_rows<100) ||")
rep('$display("PASS scanner S1 equivalence");', '$display("PASS scanner S2 equivalence");')
assert 'ref_scanner' not in s
open(dst, 'w', encoding='utf-8', newline='\n').write(s)
print('ok')
